/** CSV フィールドを安全にエスケープする。
 *
 *  2つの対策を行う:
 *   1. フォーミュラインジェクション対策: 先頭が数式トリガ文字
 *      (= + - @ TAB CR) の場合はシングルクォートを前置し、Excel / Google
 *      Sheets 等が数式として評価しないようにする。機器コンフィグ由来の
 *      任意文字列（VLAN名・ポート説明・FWルール名など）が入り得るため必要。
 *   2. 通常のCSVクォート: 値に `"` / `,` / 改行 を含む場合はダブルクォートで
 *      囲み、内部の `"` を `""` にエスケープする。 */
export function csvEscape(v: unknown): string {
  let s = String(v ?? "");
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
